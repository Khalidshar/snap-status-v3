"""One story per event inside a bulletin (owner repair 11 Nov 2026)."""

from studio_core.production.parsing import same_topic

FRANCE = [
    "طلاب يغلقون عشرات المدارس بفرنسا في إطار الاحتجاجات… وماكرون يندّد بأعمال العنف "
    "ندّد الرئيس الفرنسي إيمانويل ماكرون، الثلاثاء، بأعمال العنف التي استهدفت معلّمين",
    "فرنسا: بدعوة من ائتلاف نقابي... طلاب يغلقون عشرات المدارس في يوم احتجاجي جديد "
    "تستمر في فرنسا الاحتجاجات المطالبة بتحسين ظروف الدراسة والتصدي لغلاء المعيشة",
    "ما تداعيات الاحتجاجات والإضرابات في فرنسا على اقتصاد البلاد؟ وهل تستجيب الحكومة "
    "لمطالب المحتجين؟ نسلط الضوء على تداعيات موجة الاحتجاجات والإضرابات",
]
OTHERS = [
    "حزب آيزنكوت يقدّم مشروع قانون في الكنيست للتحقيق بهجمات ٧ أكتوبر وأثارت احتجاجات واسعة",
    "الدفاعات السعودية تُدمِّر باليستياً حوثياً باتجاه المنطقة الجنوبية فجر الثلاثاء",
    "ولي العهد السعودي ورئيس وزراء كندا يستعرضان التعاون المشترك مع الأمير محمد بن سلمان",
    "ترامب يستبعد تجدد الحرب مع إيران.. والسعودية تعلن استهداف خط أنابيب نفطي عقب محادثات "
    "مع رئيس الوزراء وزير الخارجية القطري الشيخ محمد بن عبد الرحمن آل ثاني",
    "النفط يتراجع دون 90 دولاراً للمرة الأولى منذ أغسطس",
    "برنت يهبط دون 92 دولاراً مع تهدئة ترمب مخاوف التصعيد مع إيران",
]


def test_one_event_from_two_publishers_is_one_topic():
    assert same_topic(FRANCE[1], [FRANCE[0]])
    assert same_topic(FRANCE[2], [OTHERS[0], FRANCE[0], FRANCE[1]])


def test_different_events_stay_separate():
    for index, story in enumerate(OTHERS):
        assert not same_topic(story, [FRANCE[0], *OTHERS[:index], *OTHERS[index + 1 :]])
    assert not same_topic(FRANCE[0], [])
