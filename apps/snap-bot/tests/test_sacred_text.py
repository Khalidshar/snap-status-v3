"""Exact text preservation, Pango argv/isolation and height admission."""

import hashlib
import shutil
import struct
import subprocess
import zlib
from pathlib import Path
from xml.etree import ElementTree as ET

import pytest

from snap_bot import faith, sacred_text

REPO = Path(__file__).resolve().parents[3]
FONT = REPO / "assets/fonts/notonaskharabic/NotoNaskhArabic-Regular.ttf"


@pytest.mark.parametrize("kind", faith.KINDS)
@pytest.mark.parametrize("limit", (80, 120, 240))
def test_pages_preserve_all_faith_text(kind: str, limit: int) -> None:
    for item in faith.load(kind):
        original = faith.text(item)
        chunks = sacred_text.pages(original, limit)
        combined = " ".join(chunks)
        assert combined == original
        assert (
            hashlib.sha256(combined.encode()).digest() == hashlib.sha256(original.encode()).digest()
        )
        assert all(len(chunk) <= limit for chunk in chunks)


@pytest.mark.parametrize("value", (" word ", "one  two   three", "   ", "a ", " a", "آ ﷺ أَ\u06dd١"))
def test_spaces_and_marks_are_preserved(value: str) -> None:
    for limit in (5, 8, 20):
        assert " ".join(sacred_text.pages(value, limit)) == value


@pytest.mark.parametrize("limit", (0, -1, True))
def test_bad_page_limit(limit: int) -> None:
    with pytest.raises(ValueError):
        sacred_text.pages("word", limit)


def test_unbreakable_word_rejected() -> None:
    with pytest.raises(ValueError, match="Word exceeds"):
        sacred_text.pages("unbreakable", 3)


@pytest.mark.parametrize("control", ("\n", "\r", "\t", "\0", "\x7f", "\u202e", "\u2067", "\u200f"))
def test_controls_rejected_without_execution(tmp_path: Path, control: str) -> None:
    with pytest.raises(ValueError, match="Control character"):
        sacred_text.pages("text" + control, 20)
    with pytest.raises(ValueError, match="Control character"):
        sacred_text.render_text_png(
            "text" + control, FONT, tmp_path / "out.png", pango_view="missing", max_height_px=100
        )


def png(width: int, height: int) -> bytes:
    def chunk(kind: bytes, data: bytes) -> bytes:
        return (
            struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))
        )

    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0))
        + chunk(b"IDAT", zlib.compress(b"\0" * (height * (1 + 4 * width))))
        + chunk(b"IEND", b"")
    )


@pytest.mark.parametrize("height,limit", ((60, 100), (100, 100), (101, 100)))
def test_pango_args_isolation_and_height(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, height: int, limit: int
) -> None:
    # Synthetic text includes markup-looking characters; they must stay literal.
    original = "أَ آ ﷺ <span> نص \u06dd١"
    output = tmp_path / "output.png"
    output.write_bytes(b"existing output")
    calls = []
    environments = []
    temporary_paths = []

    def which(name: str) -> str:
        return "/usr/bin/" + name

    def run(args: list[str], **kwargs: object) -> subprocess.CompletedProcess[str]:
        calls.append(args)
        env = kwargs["env"]
        assert isinstance(env, dict)
        environments.append(env)
        assert kwargs["check"] is True and kwargs["timeout"] in (5, 30)
        assert "shell" not in kwargs
        config_path = Path(env["FONTCONFIG_FILE"])
        # Only the XML just generated by this module in its private temp directory.
        config = ET.parse(config_path).getroot()  # noqa: S314
        assert config.find("include") is None
        dirs = config.findall("dir")
        assert len(dirs) == 1 and dirs[0].text
        isolated = Path(dirs[0].text)
        files = list(isolated.iterdir())
        assert len(files) == 1 and files[0].read_bytes() == FONT.read_bytes()
        assert env["PANGOCAIRO_BACKEND"] == "fontconfig"
        assert env["FONTCONFIG_PATH"] == str(config_path.parent)
        temporary_paths.append(config_path.parent)
        if args[0].endswith("fc-query"):
            assert args[1:] == ["--format=%{family}", str(files[0])]
            return subprocess.CompletedProcess(args, 0, "Noto Naskh Arabic\n", "")
        for flag in (
            "--no-display",
            "--rtl",
            "--align=center",
            "--wrap=word",
            "--background=transparent",
            "--dpi=72",
            "--pixels",
            "--width=820",
            "--font=Noto Naskh Arabic 44",
            "--foreground=#F6EEDE",
        ):
            assert flag in args
        assert "--markup" not in args and not any(a.startswith("--text=") for a in args)
        assert args[-2] == "--"
        assert Path(args[-1]).read_bytes() == original.encode("utf-8")
        rendered = Path(next(a.split("=", 1)[1] for a in args if a.startswith("--output=")))
        rendered.write_bytes(png(820, height))
        return subprocess.CompletedProcess(args, 0, "", "")

    monkeypatch.setattr(sacred_text.shutil, "which", which)
    monkeypatch.setattr(sacred_text.subprocess, "run", run)
    if height > limit:
        with pytest.raises(ValueError, match="maximum height"):
            sacred_text.render_text_png(
                original, FONT, output, pango_view="pango-view", max_height_px=limit
            )
        assert output.read_bytes() == b"existing output"
    else:
        assert sacred_text.render_text_png(
            original, FONT, output, pango_view="pango-view", max_height_px=limit
        ) == (820, height)
        assert output.read_bytes() == png(820, height)
    assert len(calls) == 2 and environments[0] == environments[1]
    assert all(not p.exists() for p in temporary_paths)


@pytest.mark.parametrize(
    "options",
    (
        {"max_height_px": 0},
        {"max_height_px": 10, "width_px": True},
        {"max_height_px": 10, "font_size": -1},
        {"max_height_px": 10, "color": "bad"},
    ),
)
def test_bad_render_options(tmp_path: Path, options: dict) -> None:
    with pytest.raises(ValueError):
        sacred_text.render_text_png(
            "text", FONT, tmp_path / "out.png", pango_view="missing", **options
        )


def test_real_pango_when_available(tmp_path: Path) -> None:
    executable = shutil.which("pango-view")
    if executable is None:
        pytest.skip("pango-view not installed locally or in this CI runner")
    # Use a verbatim stored narration; never create or rewrite religious text.
    text = faith.text(faith.load("hadith")[0])
    dimensions = sacred_text.render_text_png(
        text, FONT, tmp_path / "out.png", pango_view=executable, max_height_px=1500
    )
    assert dimensions[0] > 0 and 0 < dimensions[1] <= 1500
